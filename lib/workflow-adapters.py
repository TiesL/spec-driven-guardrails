"""Private implementation of the generation and drift command Interfaces."""
from pathlib import Path
import sys
from managed_blocks import BEGIN, END, Conflict, block, managed, framed

HEADER = b'<!-- Generated by generate-workflow-adapters.sh; edit policy/WORKFLOW.md or adapters/*/INSTRUCTIONS.md. -->\n\n'
OUTPUTS = {'WORKFLOW.md': 'adapters/claude/INSTRUCTIONS.md',
           'adapters/codex/AGENTS.md': 'adapters/codex/INSTRUCTIONS.md'}
OWNERS = ('policy/WORKFLOW.md', 'skills/role-contracts/SKILL.md',
          'skills/role-contracts/ORCHESTRATOR.md', 'skills/model-choice/SKILL.md', 'CHANGES.md')

def generated(root, mapping):
    return HEADER + (root / 'policy/WORKFLOW.md').read_bytes() + b'\n' + (root / mapping).read_bytes()

def main():
    mode = sys.argv[1]
    if len(sys.argv) > 3:
        print('workflow adapters: invalid arguments', file=sys.stderr); return 2
    root = Path(sys.argv[2]) if len(sys.argv) == 3 else Path(__file__).resolve().parent.parent
    if not root.is_dir():
        print('workflow adapters: invalid/unreadable directory: ' + str(root), file=sys.stderr); return 2
    root_path = root / 'AGENTS.md'
    if root_path.is_symlink() or (root_path.exists() and not root_path.is_file()):
        raise ValueError('root AGENTS.md: expected a regular file, not a symlink')
    data = root_path.read_bytes() if root_path.exists() else b''
    span = block(data, BEGIN, END, 'root AGENTS.md')
    if root_path.exists() and span is None:
        raise ValueError('root AGENTS.md: missing managed markers')
    missing = []
    for name in (*OWNERS, *OUTPUTS.values()):
        p = root / name
        if p.exists() and not p.is_file():
            raise ValueError('invalid contract: ' + name + ': expected a regular file')
        if not p.is_file():
            print('workflow adapters: missing contract: ' + name); missing.append(name)
        else:
            try: p.read_bytes()
            except OSError as exc:
                print('workflow adapters: unreadable ' + name + ': ' + str(exc)); return 2
    errors = len(missing)
    for output, mapping in OUTPUTS.items():
        if 'policy/WORKFLOW.md' in missing or mapping in missing:
            if mode == 'check': print('workflow adapters: cannot verify ' + output)
            continue
        wanted = generated(root, mapping)
        path = root / output
        if mode == 'generate':
            if errors: continue
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(wanted)
        elif not path.is_file():
            print('workflow adapters: missing output: ' + output); errors += 1
        elif path.read_bytes() != wanted:
            print('workflow adapters: drift: ' + output); errors += 1
    if mode == 'generate':
        if not errors:
            payload = generated(root, OUTPUTS['adapters/codex/AGENTS.md'])
            root_path.write_bytes(managed(data, span, framed(payload)))
    elif not root_path.exists():
        print('workflow adapters: missing output: root AGENTS.md (source adapters/codex/AGENTS.md)'); errors += 1
    elif (root / 'adapters/codex/AGENTS.md').is_file():
        expected = framed((root / 'adapters/codex/AGENTS.md').read_bytes())
        if data[span[0]:span[1]] != expected:
            print('workflow adapters: drift: root AGENTS.md (source adapters/codex/AGENTS.md)'); errors += 1
    return 1 if errors else 0

if __name__ == '__main__':
    try: sys.exit(main())
    except (OSError, ValueError, Conflict) as exc:
        print('workflow adapters: ' + str(exc), file=sys.stderr); sys.exit(2)
